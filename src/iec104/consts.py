"""IEC 60870-5-104 常量表（本项目实际用到的子集）。

⚠️ 纪律：本文件里每个数值都必须能指回标准原文。
   首次定稿前要逐条核对；这里先按实测抓包与公开标准整理，未核对项标 [待核对]。
   ⚠️ 不要凭记忆改这里的值——改错一个字节整个会话就废了。

参考实测：`_p2_iec104/实测抓包-104.md`（8 帧真实报文）
"""

from enum import IntEnum


# ---------------------------------------------------------------- 帧格式
class FrameFormat(IntEnum):
    """APCI 控制域的三种格式（由控制域第一个字节的低 2 位判定）。"""

    I = 0b00  # 信息帧：承载 ASDU
    S = 0b01  # 监视帧：只确认接收序号
    U = 0b11  # 未编号帧：链路控制（启动/停止/测试）


class UFrame(IntEnum):
    """U 格式帧的控制字节取值。实测：STARTDT act=0x07、con=0x0B。"""

    STARTDT_ACT = 0x07
    STARTDT_CON = 0x0B
    STOPDT_ACT = 0x13
    STOPDT_CON = 0x23
    TESTFR_ACT = 0x43
    TESTFR_CON = 0x83


# ---------------------------------------------------------------- 类型标识
class TypeID(IntEnum):
    """应用层数据类型标识（TypeID）。

    ⚠️ 只列本项目用到的；其余类型按标准原文补，不要臆造编号。
    """

    M_SP_NA_1 = 1     # 单点信息（遥信）
    M_SP_TB_1 = 30    # 带 CP56Time2a 时标的单点信息（SOE）
    M_ME_NA_1 = 9     # 归一化测量值
    M_ME_NC_1 = 13    # 短浮点测量值（遥测）⭐ 实测 23.7 = 9A 99 BD 41（小端）
    C_SC_NA_1 = 45    # 单点命令（遥控）
    C_SE_NC_1 = 50    # 短浮点设定值（遥调）
    C_IC_NA_1 = 100   # 总召唤
    C_CS_NA_1 = 103   # 时钟同步（对时）


# ---------------------------------------------------------------- 传送原因
class COT(IntEnum):
    """传送原因（Cause Of Transmission）。

    实测确认的：1 周期、6 激活、7 激活确认、10 激活终止、20 响应站召唤。
    其余按标准原文补。
    """

    PERIODIC = 1                    # 周期/循环
    BACKGROUND = 2                  # 背景扫描
    SPONTANEOUS = 3                 # 突发（变位）
    INITIALIZED = 4                 # 初始化
    REQUEST = 5                     # 请求
    ACTIVATION = 6                  # 激活
    ACTIVATION_CONFIRM = 7          # 激活确认
    DEACTIVATION = 8                # 停止激活
    DEACTIVATION_CONFIRM = 9        # 停止激活确认
    ACTIVATION_TERMINATION = 10     # 激活终止
    CAUSE_UNKNOWN = 44              # 未知的传送原因
    INTERROGATED_BY_STATION = 20    # 响应站总召唤
    UNKNOWN_TYPE_ID = 44
    UNKNOWN_CA = 45                 # 公共地址未知
    UNKNOWN_IOA = 46                # 信息对象地址未知


# COT 高位标志
COT_PN_BIT = 0x40   # 否定确认位（1=否定）
COT_TEST_BIT = 0x80  # 试验位


# ---------------------------------------------------------------- 品质位
class QDS(IntEnum):
    """品质描述词（遥测用）。0 表示品质良好。

    ⚠️ 位定义需按标准原文逐位核对；这里按常用约定给位掩码。
    """

    OV = 0x01  # 溢出
    BL = 0x10  # 被闭锁
    SB = 0x20  # 被取代
    NT = 0x40  # 非当前值（不新鲜）
    IV = 0x80  # 无效（值不可用）


class SIQ:
    """单点信息品质描述词（遥信用，1 字节）。

    bit0 = SPI（值），bit4~7 = 品质（BL/SB/NT/IV）。
    ⚠️ 位定义需按标准原文核对。
    """

    SPI = 0x01   # 单点值：0=分，1=合
    BL = 0x10
    SB = 0x20
    NT = 0x40
    IV = 0x80


class SCO:
    """单点命令（遥控）限定词，1 字节。

    bit0 = SCS（命令状态），bit7 = S/E（0=执行，1=选择）。
    ⚠️ S/E 位位置需按标准原文核对——写反了遥控永远通不了。
    """

    SCS = 0x01
    SE = 0x80   # 选择/执行：1=选择(select)，0=执行(execute)
    QU_MASK = 0x1F


# ---------------------------------------------------------------- 会话参数
class SessionParam:
    """链路层参数。⚠️ 默认值按标准常用值，实际部署以对端协商为准。"""

    K = 12          # 未被确认的 I 帧上限（发送窗口）
    W = 8           # 收到多少个 I 帧就发确认
    T0 = 30.0       # 连接建立超时（秒）
    T1 = 15.0       # 发送后等确认超时（秒）
    T2 = 10.0       # 未确认超过该时长就发 S 帧（秒）
    T3 = 20.0       # 空闲这么久就发 TESTFR（秒）

    SEQ_MOD = 32768  # 序号模（15 位）


# ---------------------------------------------------------------- 公共地址
BROADCAST_CA = 0xFFFF   # ⭐ 广播公共地址。实测 c104 客户端总召唤就发 FF FF
